// Get login reports with filters - UPDATED for your table structure
export const getLoginReports = async (filters = {}) => {
  try {
    let query = supabase
      .from("login_reports")
      .select("*")
      .order("login_date", { ascending: false })
      .order("login_time", { ascending: false });

    // Apply filters
    if (filters.startDate) {
      query = query.gte("login_date", filters.startDate);
    }
    if (filters.endDate) {
      query = query.lte("login_date", filters.endDate);
    }
    if (filters.studentId) {
      query = query.eq("student_id", filters.studentId);
    }

    const { data, error } = await query;

    if (error) {
      console.error("Error fetching login reports:", error);
      return { success: false, message: "Error fetching login reports" };
    }

    return { success: true, data };
  } catch (error) {
    console.error("Error fetching login reports:", error);
    return { success: false, message: "Error fetching login reports" };
  }
};

// Get login statistics - UPDATED for your table structure
export const getLoginStatistics = async (days = 7) => {
  try {
    const endDate = new Date();
    const startDate = new Date();
    startDate.setDate(startDate.getDate() - days);

    const { data, error } = await supabase
      .from("login_reports")
      .select("*")
      .gte("login_date", startDate.toISOString().split('T')[0])
      .lte("login_date", endDate.toISOString().split('T')[0]);

    if (error) {
      console.error("Error fetching statistics:", error);
      return { success: false, message: "Error fetching statistics" };
    }

    // Process statistics
    const dailyStats = {};
    const hourlyDistribution = Array(24).fill(0);
    
    data.forEach(record => {
      // Daily stats
      if (!dailyStats[record.login_date]) {
        dailyStats[record.login_date] = {
          date: record.login_date,
          total: 0,
          uniqueStudents: new Set()
        };
      }
      dailyStats[record.login_date].total++;
      dailyStats[record.login_date].uniqueStudents.add(record.student_id); // Use student_id instead of student_uuid

      // Hourly distribution
      const hour = parseInt(record.login_time.split(':')[0]);
      hourlyDistribution[hour]++;
    });

    // Convert Sets to counts
    Object.values(dailyStats).forEach(stat => {
      stat.uniqueStudents = stat.uniqueStudents.size;
    });

    return { 
      success: true, 
      data: {
        daily: Object.values(dailyStats),
        hourly: hourlyDistribution,
        total: data.length,
        uniqueStudents: new Set(data.map(r => r.student_id)).size // Use student_id
      }
    };
  } catch (error) {
    console.error("Error processing statistics:", error);
    return { success: false, message: "Error processing statistics" };
  }
};