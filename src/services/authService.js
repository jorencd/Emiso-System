// Record student login for reporting - FIXED for your table structure
export const recordStudentLogin = async (studentData) => {
  try {
    const today = new Date();
    const loginDate = today.toISOString().split('T')[0]; // YYYY-MM-DD
    const loginTime = today.toTimeString().split(' ')[0]; // HH:MM:SS

    console.log("Attempting to record login for:", studentData.student_id);

    // Check if student already logged in today using student_id
    const { data: existingLog, error: checkError } = await supabase
      .from("login_reports")
      .select("id")
      .eq("student_id", studentData.student_id)
      .eq("login_date", loginDate)
      .maybeSingle();

    if (checkError) {
      console.error("Error checking existing login:", checkError);
      return;
    }

    // If no record exists for today, insert new login record
    if (!existingLog) {
      console.log("Inserting new login record for:", studentData.student_id);
      
      const { error } = await supabase
        .from("login_reports")
        .insert([
          {
            student_id: studentData.student_id,  // Use student_id only (no student_uuid)
            first_name: studentData.first_name,
            last_name: studentData.last_name,
            login_date: loginDate,
            login_time: loginTime,
            // created_at will be auto-generated by default value
          },
        ]);

      if (error) {
        console.error("Error recording login:", error);
      } else {
        console.log("✅ Login recorded successfully for:", studentData.student_id);
      }
    } else {
      console.log("Student already logged in today:", studentData.student_id);
    }
  } catch (error) {
    console.error("Failed to record login:", error);
  }
};

// LOGIN - Compare hashed password
export const loginStudent = async (studentId, password) => {
  try {
    const { data, error } = await supabase
      .from("students")
      .select("*")
      .eq("student_id", studentId)
      .single();

    if (error || !data) {
      console.error("Login error:", error);
      return { success: false, message: "Invalid login credentials" };
    }

    // Compare the provided password with the hashed password
    const isPasswordValid = await bcrypt.compare(password, data.password);
    
    if (!isPasswordValid) {
      return { success: false, message: "Invalid login credentials" };
    }

    // Record the login (don't await to not delay login response)
    recordStudentLogin(data).catch(err => 
      console.error("Background login recording failed:", err)
    );

    // Remove password from returned data
    const { password: _, ...userWithoutPassword } = data;
    
    return { 
      success: true, 
      data: userWithoutPassword,
      message: "Login successful" 
    };
  } catch (error) {
    console.error("Login error:", error);
    return { success: false, message: "An error occurred during login" };
  }
};

// REGISTER - Hash password before storing
export const registerStudent = async (form) => {
  try {
    // Check if student ID already exists
    const { data: existing, error: checkError } = await supabase
      .from("students")
      .select("student_id")
      .eq("student_id", form.studentId)
      .maybeSingle();

    if (checkError) {
      console.error("Error checking student ID:", checkError);
      return { success: false, message: "Error checking student ID" };
    }

    if (existing) {
      return { success: false, message: "Student ID already registered" };
    }

    // Hash the password
    const saltRounds = 10;
    const hashedPassword = await bcrypt.hash(form.password, saltRounds);

    // Insert new student with hashed password
    const { data, error } = await supabase
      .from("students")
      .insert([
        {
          student_id: form.studentId,
          first_name: form.firstName,
          middle_name: form.middleName || null,
          last_name: form.lastName,
          course: form.course,
          password: hashedPassword,
        },
      ])
      .select()
      .single();

    if (error) {
      console.error("Registration error:", error);
      return { success: false, message: error.message };
    }

    return { 
      success: true, 
      data,
      message: "Registration successful" 
    };
  } catch (error) {
    console.error("Registration error:", error);
    return { success: false, message: "Error creating account" };
  }
};

